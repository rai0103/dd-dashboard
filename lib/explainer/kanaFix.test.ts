// 実行: node --test lib/explainer/kanaFix.test.ts
import { test } from "node:test";
import assert from "node:assert/strict";
import { fixHaForTts } from "./kanaFix.ts";

test("fixHaForTts：漢字の読みの最後の「は」だけをカタカナにし、助詞の「は」はそのまま", () => {
  assert.equal(fixHaForTts("すいしんははこんごもせつめいをつづけます。", "推進派は今後も説明を続けます。"), "すいしんハはこんごもせつめいをつづけます。");
  assert.equal(fixHaForTts("あんぜんじゅうしははしんちょうです。", "安全重視派は慎重です。"), "あんぜんじゅうしハはしんちょうです。");
  assert.equal(fixHaForTts("すいしんはと、あんぜんじゅうしはが、たいりつしています。", "推進派と、安全重視派が、対立しています。"), "すいしんハと、あんぜんじゅうしハが、たいりつしています。");
  // 助詞の「は」・単語の中の「は」は変えない
  assert.equal(fixHaForTts("げんぱつとは、べつのあんぜんきじゅんです。", "原発とは、別の安全基準です。"), "げんぱつとは、べつのあんぜんきじゅんです。");
  assert.equal(fixHaForTts("じみんとうがりょうしょうしたほうあんは、なにをめざすのでしょうか。", "自民党が了承した法案は、何を目指すのでしょうか。"), "じみんとうがりょうしょうしたほうあんは、なにをめざすのでしょうか。");
  assert.equal(fixHaForTts("はけんしゃいんは、はじめてです。", "派遣社員は、初めてです。"), "はけんしゃいんは、はじめてです。");
  assert.equal(fixHaForTts("かれははなしました。", "彼は話しました。"), "かれははなしました。");
  assert.equal(fixHaForTts("すいしんははなしあいをもとめています。", "推進派は話し合いを求めています。"), "すいしんハはなしあいをもとめています。");
  assert.equal(fixHaForTts("にほんははっぴょうしました。", "日本は発表しました。"), "にほんははっぴょうしました。");
  assert.equal(fixHaForTts("ろうれいかはは、はやくなっています。", "老齢化派は、早くなっています。"), "ろうれいかハは、はやくなっています。");
  // 「は」が無ければそのまま
  assert.equal(fixHaForTts("きょうのにゅーすです。", "今日のニュースです。"), "きょうのにゅーすです。");
});

test("fixHaForTts：長い文・派のない文は変えない", () => {
  const n = "原発とは別の安全基準で、軽い原子核同士を合体させて膨大な熱を生む反応である核融合を育てる。自民党が了承した法案は、何を目指すのでしょうか。";
  const r = "げんぱつとは、べつのあんぜんきじゅんで、かるいげんしかくどうしをがったいさせてぼうだいなねつをうむはんのうであるかくゆうごうをそだてる。じみんとうがりょうしょうしたほうあんは、なにをめざすのでしょうか。";
  assert.equal(fixHaForTts(r, n), r);
  assert.equal(fixHaForTts("すいしんはのぎいんは、さんせいです。", "推進派の議員は、賛成です。"), "すいしんハのぎいんは、さんせいです。");
});
